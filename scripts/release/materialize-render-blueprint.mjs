#!/usr/bin/env node
import { writeFile } from 'node:fs/promises'

const DIGEST_RE = /^sha256:[a-f0-9]{64}$/

export function normalizeDigest(value) {
  const digest = String(value ?? '').trim().toLowerCase()
  if (!DIGEST_RE.test(digest)) {
    throw new Error('Expected an immutable sha256 digest (sha256:<64 lowercase hex>)')
  }
  return digest
}

const flags = [
  'CMS_AUTH_ENABLED',
  'CATALOG_SCAN_ENABLED',
  'COLLECTIONS_ADMIN_ENABLED',
  'COLLECTOR_ASSOCIATION_READ_ENABLED',
  'COLLECTOR_DRAFT_MUTATION_ENABLED',
  'CONSUMER_CREDENTIALS_ENABLED',
  'COLLECTIONS_DISTRIBUTION_ENABLED',
]

function flagEnv(indent = '      ') {
  return flags.map((key) => `${indent}- key: ${key}\n${indent}  value: "false"`).join('\n')
}

function secretEnv(keys, indent = '      ') {
  return keys.map((key) => `${indent}- key: ${key}\n${indent}  sync: false`).join('\n')
}

export function buildBlueprint({ apiDigest, adminDigest }) {
  const api = normalizeDigest(apiDigest)
  const admin = normalizeDigest(adminDigest)
  return `# Generated by scripts/release/materialize-render-blueprint.mjs.
# Do not hand-edit image URLs: they must be real registry digests produced by a successful build.
services:
  - type: web
    runtime: static
    name: Concierge-Collector-Web
    buildCommand: corepack enable && corepack prepare npm@10.9.2 --activate && npm ci --legacy-peer-deps && npm run build:collector
    staticPublishPath: dist/collector
    domains:
      - concierge-collector.com
      - www.concierge-collector.com
    autoDeployTrigger: checksPass

  - type: web
    runtime: image
    name: Concierge-Collector-API-V3
    image:
      url: ghcr.io/wsmontes/concierge-api@${api}
    dockerCommand: uvicorn main:app --host 0.0.0.0 --port $PORT
    healthCheckPath: /api/v3/ready
    domains:
      - api.concierge-collector.com
      - capture.concierge-collector.com
    maxShutdownDelaySeconds: 60
    envVars:
      - key: ENVIRONMENT
        value: production
      - key: MONGODB_DB_NAME
        value: concierge-collector
      - key: CMS_MONGODB_DB_NAME
        value: concierge-cms
${secretEnv(['MONGODB_URL', 'CMS_MONGODB_READ_URL', 'CMS_SERVICE_KEY', 'METRICS_KEY', 'API_SECRET_KEY', 'JWT_SIGNING_SECRET', 'GOOGLE_OAUTH_CLIENT_ID', 'GOOGLE_OAUTH_CLIENT_SECRET', 'OPENAI_API_KEY', 'CATALOG_CURSOR_SECRET', 'DISTRIBUTION_CURSOR_SECRET', 'AUDIT_S3_ENDPOINT', 'AUDIT_S3_REGION', 'AUDIT_S3_BUCKET', 'AUDIT_S3_ACCESS_KEY_ID', 'AUDIT_S3_SECRET_ACCESS_KEY'])}
${flagEnv()}

  - type: web
    runtime: image
    name: Concierge-Collector-Admin
    image:
      url: ghcr.io/wsmontes/concierge-admin@${admin}
    dockerCommand: npm run start:admin -- --port $PORT
    preDeployCommand: npm run migrate:cms:locked
    healthCheckPath: /ready
    domains:
      - admin.concierge-collector.com
    maxShutdownDelaySeconds: 60
    envVars:
      - key: CMS_MONGODB_DB_NAME
        value: concierge-cms
      - key: FASTAPI_BASE_URL
        value: https://api.concierge-collector.com
      - key: CMS_PUBLIC_SERVER_URL
        value: https://admin.concierge-collector.com
      - key: CMS_COLLECTOR_ORIGINS
        value: https://concierge-collector.com
${secretEnv(['CMS_MONGODB_URL', 'CMS_SERVICE_KEY', 'PAYLOAD_SECRET', 'METRICS_KEY', 'S3_ENDPOINT', 'S3_REGION', 'S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY', 'S3_EXPORT_PREFIX', 'S3_SIGNED_URL_TTL_SECONDS', 'EXPORT_ARTIFACT_TTL_SECONDS'])}
${flagEnv()}

  - type: worker
    runtime: image
    name: Concierge-Collector-Admin-Worker
    image:
      url: ghcr.io/wsmontes/concierge-admin@${admin}
    dockerCommand: npm run start:admin-worker
    maxShutdownDelaySeconds: 300
    envVars:
      - key: CMS_MONGODB_DB_NAME
        value: concierge-cms
      - key: FASTAPI_BASE_URL
        value: https://api.concierge-collector.com
      - key: CMS_PUBLIC_SERVER_URL
        value: https://admin.concierge-collector.com
      - key: CMS_COLLECTOR_ORIGINS
        value: https://concierge-collector.com
${secretEnv(['CMS_MONGODB_URL', 'CMS_SERVICE_KEY', 'PAYLOAD_SECRET', 'METRICS_KEY', 'S3_ENDPOINT', 'S3_REGION', 'S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY', 'S3_EXPORT_PREFIX', 'S3_SIGNED_URL_TTL_SECONDS', 'EXPORT_ARTIFACT_TTL_SECONDS'])}
${flagEnv()}
`
}

function arg(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const apiDigest = arg('--api-digest')
  const adminDigest = arg('--admin-digest')
  const output = arg('--output') || 'render.yaml'
  const yaml = buildBlueprint({ apiDigest, adminDigest })
  await writeFile(output, yaml, { encoding: 'utf8', flag: 'w' })
  process.stdout.write(`materialized ${output} with immutable image digests\n`)
}
